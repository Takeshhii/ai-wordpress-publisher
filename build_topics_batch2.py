def write_csv(path, project, site, style, blocks, rows):
    with open(path, "w", encoding="utf-8-sig", newline="") as f:
        w = csv.writer(f)
        w.writerow(HEADER)
        for i, r in enumerate(rows, 1):
            ct, title, h1, mk, sec, intent, cat, tags, links, wc, outline = r
            secondary = ", ".join(sec)
            required = f"{blocks}; каркас: {outline}"
            w.writerow([mk, site, project, ct, title, h1, mk, secondary,
                        intent, cat, tags, " | ".join(links), wc, required,
                        style, "draft", i])
    return len(rows)


